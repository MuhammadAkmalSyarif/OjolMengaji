/**
 * Normalizes input string for fuzzy comparison
 */
export const normalizeBankSearch = (str: string): string => {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '')
    .trim();
};

/**
 * Finds a matching BankInfo object by full name, shortName, id, or alias
 */
export const findBank = (query?: string): BankInfo | undefined => {
  if (!query) return undefined;
  const clean = query.trim().toLowerCase();
  const normalized = normalizeBankSearch(query);

  // Exact match by name, shortName, id
  const direct = ALL_BANKS.find(
    b =>
      b.name.toLowerCase() === clean ||
      b.shortName.toLowerCase() === clean ||
      b.id.toLowerCase() === clean
  );
  if (direct) return direct;

  // Search by alias or normalized inclusion
  return ALL_BANKS.find(b => {
    if (normalizeBankSearch(b.name) === normalized) return true;
    if (normalizeBankSearch(b.shortName) === normalized) return true;
    return b.aliases.some(a => {
      const aNorm = normalizeBankSearch(a);
      return aNorm === normalized || normalized.includes(aNorm) || aNorm.includes(normalized);
    });
  });
};

/**
 * Returns brand colors for a bank name
 */
export const getBankColors = (bankName?: string) => {
  const bank = findBank(bankName);
  if (bank) {
    return {
      brandColor: bank.brandColor,
      bgLight: bank.bgLight,
      textColor: bank.textColor,
    };
  }
  return {
    brandColor: '#10B981',
    bgLight: '#ECFDF5',
    textColor: '#065F46',
  };
};

